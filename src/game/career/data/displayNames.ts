/** Confederation keys stay internal; the picker shows geography only. */
export const CONFEDERATION_DISPLAY_NAMES: Record<string, string> = {
  UEFA: 'Europe',
  CONMEBOL: 'South America',
  CONCACAF: 'North America',
  CAF: 'Africa',
  AFC: 'Asia',
  OFC: 'Oceania',
};

export function confederationDisplayName(id: string | null | undefined): string {
  if (!id) return '';
  return CONFEDERATION_DISPLAY_NAMES[id] ?? id;
}

let aliasPairs: [string, string][] | null = null;

function licensedAliasPairs(): [string, string][] {
  if (!aliasPairs) {
    aliasPairs = Object.entries(LICENSED_DISPLAY_ALIASES)
      .filter(([from, to]) => from !== to)
      .sort((a, b) => b[0].length - a[0].length);
  }
  return aliasPairs;
}

function replaceLicensedPhrase(haystack: string, from: string, to: string): string {
  if (!haystack.includes(from)) return haystack;
  if (!to.includes(from)) return haystack.split(from).join(to);
  const pieces = haystack.split(from);
  let out = pieces[0] ?? '';
  for (let i = 1; i < pieces.length; i++) {
    const already = (out + from).endsWith(to);
    out += (already ? from : to) + (pieces[i] ?? '');
  }
  return out;
}

/** Rewrite leftover licensed wording in stored copy, match recaps, and beats. */
export function rewriteLicensedDisplayText(value: string | null | undefined): string {
  if (!value) return value ?? '';
  let next = value;
  for (const [from, to] of licensedAliasPairs()) {
    next = replaceLicensedPhrase(next, from, to);
  }
  return next;
}

export function migrateTrophyName(name: string): string {
  return LICENSED_DISPLAY_ALIASES[name] ?? LEAGUE_DISPLAY_NAMES[name] ?? rewriteLicensedDisplayText(name);
}
